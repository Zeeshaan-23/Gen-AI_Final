"""
CatalogUpdate AI - Specification Line Parser.

Parses natural language furniture specification update lines generated by the
CharLSTM model (or entered manually by users) into structured attribute fields:
- part: Target furniture sub-component (e.g. 'chair legs', 'table top').
- color: Target color attribute (e.g. 'dark', 'charcoal', 'emerald').
- material: Target material attribute (e.g. 'walnut', 'black leather', 'marble').
- finish: Target finish attribute (e.g. 'matte', 'glossy', 'satin').

Connects generated text directly to the diffusion prompt composition engine.
"""

import re
from typing import Dict, Optional

from src.text.make_corpus import PARTS, MATERIALS, COLORS, FINISHES


def parse_spec_line(line: str) -> Dict[str, Optional[str]]:
    """
    Parses a specification update line into structured components with robust fallback.

    Supported patterns:
    - "Update: <part> changed to <color> <material>, <finish> finish."
    - "Update: change <part> to <color> <material> with <finish> finish."
    - "Change: replace <part> with <color> <material>, <finish> finish."
    - "Spec update: <part> updated to <color> <material>, <finish> finish."
    - "Update: <part> modified to <material> in <color>, <finish> finish."

    Args:
        line: Generated or user-entered specification string.

    Returns:
        Dict containing keys: 'part', 'color', 'material', 'finish'.
    """
    cleaned = line.strip().strip(".! \t\n")
    cleaned_lower = cleaned.lower()

    # 1. Regex Template Matching
    # Pattern A: "Update: <part> changed to / updated to / to <spec>"
    match_a = re.search(
        r"^(?:update|change|spec update):\s*(?:change\s+|replace\s+)?(.*?)\s+(?:changed to|updated to|modified to|with|to)\s+(.*)$",
        cleaned_lower,
        re.IGNORECASE,
    )

    detected_part: Optional[str] = None
    detected_color: Optional[str] = None
    detected_material: Optional[str] = None
    detected_finish: Optional[str] = None

    if match_a:
        candidate_part = match_a.group(1).strip()
        candidate_spec = match_a.group(2).strip()

        # Check if candidate_part contains known part
        for p in sorted(PARTS, key=len, reverse=True):
            if p in candidate_part:
                detected_part = p
                break

        # Check candidate_spec for finish (e.g. "matte finish", "glossy finish")
        finish_match = re.search(r"(\w+)\s+finish", candidate_spec)
        if finish_match:
            candidate_finish = finish_match.group(1)
            for f in FINISHES:
                if f == candidate_finish:
                    detected_finish = f
                    break

        # Check candidate_spec for color and material
        for m in sorted(MATERIALS, key=len, reverse=True):
            if m in candidate_spec:
                detected_material = m
                break

        for c in sorted(COLORS, key=len, reverse=True):
            if c in candidate_spec:
                detected_color = c
                break

    # 2. Safe Fallback: Keyword search across the whole line
    if not detected_part:
        for p in sorted(PARTS, key=len, reverse=True):
            if p in cleaned_lower:
                detected_part = p
                break

    if not detected_material:
        for m in sorted(MATERIALS, key=len, reverse=True):
            if m in cleaned_lower:
                detected_material = m
                break

    if not detected_color:
        for c in sorted(COLORS, key=len, reverse=True):
            if c in cleaned_lower:
                detected_color = c
                break

    if not detected_finish:
        for f in sorted(FINISHES, key=len, reverse=True):
            if f in cleaned_lower:
                detected_finish = f
                break

    # Final defaults if completely missing
    return {
        "part": detected_part or "chair legs",
        "color": detected_color or "dark",
        "material": detected_material or "walnut",
        "finish": detected_finish or "matte",
    }
